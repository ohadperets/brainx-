#!/usr/bin/env node
// BrainX content importer — validates a content pack, de-duplicates it against
// existing content, and writes it to content-imports.js as DRAFTS.
//
// Usage:
//   node tools/import-content.mjs content/imports/<pack>.json            # import / re-import as drafts
//   node tools/import-content.mjs content/imports/<pack>.json --dry-run  # report only, write nothing
//   node tools/import-content.mjs --publish <id,id,...|pack:<dataset name>>
//   node tools/import-content.mjs --unpublish <id,id,...>
//
// Optional review file next to the pack: <pack>.review.json
//   { "reject": { "<id>": "reason" },
//     "edit":   { "<id>": { "question"?, "options"?, "correctAnswer"?, "explanation"?, "topic"?, "target"?, "note": "why" } } }
//
// Only items with status "published" are shown to students (see applyPublishedImports in app.js).
// Requires Node 18+, no dependencies.

import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const IMPORTS_FILE = path.join(ROOT, 'content-imports.js');
const GRADES = { 3: 'APP_DATA_GRADE3', 6: 'APP_DATA_GRADE6' };
const SUBJECTS = { english: 'english', hebrew: 'hebrew', math: 'math' };
// Allowed target arrays (subject-relative) — must be existing {question, options, correct} arrays.
const TARGETS = {
  3: ['hebrew.quiz', 'english.quiz', 'math.quiz', 'math.multiplicationQuiz'],
  6: ['hebrew.quiz', 'english.quiz', 'math.quiz', 'math.geometryQuiz', 'mathWordProblems'],
};

const args = process.argv.slice(2);
const flag = n => args.includes(n);
const flagVal = n => { const i = args.indexOf(n); return i >= 0 ? args[i + 1] : null; };

// ---------- helpers ----------
const norm = s => String(s ?? '').toLowerCase()
  .replace(/[‘’“”"'״׳`]/g, '')
  .replace(/[^\p{L}\p{N}]+/gu, ' ').trim();
const tokens = s => new Set(norm(s).split(' ').filter(Boolean));
const jaccard = (a, b) => {
  const A = tokens(a), B = tokens(b);
  if (!A.size || !B.size) return 0;
  let inter = 0; for (const t of A) if (B.has(t)) inter++;
  return inter / (A.size + B.size - inter);
};
const hasHebrew = s => /[֐-׿]/.test(s);

function loadExisting() {
  const ctx = {};
  vm.createContext(ctx);
  vm.runInContext(fs.readFileSync(path.join(ROOT, 'data.js'), 'utf8') +
    `;this.__G = {3: ${GRADES[3]}, 6: ${GRADES[6]}};`, ctx);
  return ctx.__G;
}

function loadImports() {
  if (!fs.existsSync(IMPORTS_FILE)) return [];
  const ctx = {};
  vm.createContext(ctx);
  vm.runInContext(fs.readFileSync(IMPORTS_FILE, 'utf8') + ';this.__I = CONTENT_IMPORTS;', ctx);
  return JSON.parse(JSON.stringify(ctx.__I));
}

function writeImports(items) {
  items.sort((a, b) => a.grade - b.grade || a.subject.localeCompare(b.subject) || a.id.localeCompare(b.id));
  const counts = items.reduce((m, i) => (m[i.status] = (m[i.status] || 0) + 1, m), {});
  const out = `// ===== CONTENT IMPORTS — generated by tools/import-content.mjs. Do not edit by hand. =====
// Imported questions. Only status "published" items reach students; "draft" items are
// visible only in the admin review screen (ניהול חידונים).
// Totals: ${Object.entries(counts).map(([k, v]) => `${k}=${v}`).join(', ') || 'none'}
const CONTENT_IMPORTS = ${JSON.stringify(items, null, 2)};
`;
  fs.writeFileSync(IMPORTS_FILE, out, 'utf8');
}

// Collect every existing question-like text per grade (all arrays, all games) for duplicate checks.
function existingQuestions(gradeData, prefix) {
  const out = [];
  const walk = (o, p) => {
    if (Array.isArray(o)) return o.forEach((x, i) => walk(x, `${p}[${i}]`));
    if (o && typeof o === 'object') {
      const text = o.question ?? o.sentence;
      if (typeof text === 'string') {
        const ans = Array.isArray(o.options) && Number.isInteger(o.correct) ? o.options[o.correct] : o.answer;
        out.push({ path: p, text, answer: ans });
      }
      for (const [k, v] of Object.entries(o)) if (v && typeof v === 'object') walk(v, `${p}.${k}`);
    }
  };
  walk(gradeData, prefix);
  return out;
}

function defaultTarget(item) {
  return `${SUBJECTS[item.subject.toLowerCase()]}.quiz`;
}

// ---------- validation ----------
function validate(item) {
  const errors = [], warnings = [];
  if (!item.id || typeof item.id !== 'string') errors.push('missing id');
  if (!GRADES[item.grade]) errors.push(`unsupported grade ${item.grade} (only 3, 6)`);
  if (!SUBJECTS[String(item.subject).toLowerCase()]) errors.push(`unsupported subject "${item.subject}"`);
  if (item.type !== 'multiple_choice') errors.push(`unsupported type "${item.type}"`);
  if (!item.question || !String(item.question).trim()) errors.push('empty question');
  const opts = item.options;
  if (!Array.isArray(opts) || opts.length < 2 || opts.length > 6) errors.push('options must be 2–6 items');
  else {
    if (opts.some(o => !String(o).trim())) errors.push('empty option');
    if (new Set(opts.map(o => norm(o) || String(o).trim())).size !== opts.length) errors.push('duplicate options');
    const matches = opts.filter(o => o === item.correctAnswer).length;
    if (matches !== 1) errors.push(`correctAnswer must match exactly one option (matched ${matches})`);
  }
  if (GRADES[item.grade] && SUBJECTS[String(item.subject).toLowerCase()]) {
    const t = item.target || defaultTarget(item);
    if (!TARGETS[item.grade].includes(t)) errors.push(`target "${t}" not allowed for grade ${item.grade}`);
  }
  if (!item.explanation) warnings.push('no explanation');
  const s = String(item.subject).toLowerCase();
  if (s === 'hebrew' && !hasHebrew(item.question)) warnings.push('Hebrew item without Hebrew text');
  if (/=\s*\?\s*=\s*\?|\?\s*=\s*\?$/.test(item.question)) warnings.push('question ends with a duplicated "= ?"');
  return { errors, warnings };
}

// ---------- publish / unpublish ----------
function setStatus(spec, status) {
  const items = loadImports();
  let ids;
  if (spec.startsWith('pack:')) {
    const name = spec.slice(5);
    ids = new Set(items.filter(i => i.pack === name).map(i => i.id));
  } else ids = new Set(spec.split(',').map(s => s.trim()).filter(Boolean));
  const unknown = [...ids].filter(id => !items.some(i => i.id === id));
  if (unknown.length) { console.error('Unknown ids:', unknown.join(', ')); process.exit(1); }
  let n = 0;
  for (const i of items) if (ids.has(i.id) && i.status !== status) { i.status = status; i.statusChangedAt = new Date().toISOString().slice(0, 10); n++; }
  writeImports(items);
  console.log(`${status === 'published' ? 'Published' : 'Unpublished'} ${n} item(s). Deploy (commit + push) to make the change live.`);
}

// ---------- main import ----------
function importPack(packPath) {
  const abs = path.resolve(packPath);
  const pack = JSON.parse(fs.readFileSync(abs, 'utf8'));
  const reviewPath = abs.replace(/\.json$/, '.review.json');
  const review = fs.existsSync(reviewPath) ? JSON.parse(fs.readFileSync(reviewPath, 'utf8')) : { reject: {}, edit: {} };
  const packName = pack.dataset || path.basename(abs, '.json');

  const G = loadExisting();
  const existing = { 3: existingQuestions(G[3], 'GRADE3'), 6: existingQuestions(G[6], 'GRADE6') };
  const prior = loadImports();
  const priorById = new Map(prior.map(i => [i.id, i]));

  const result = { imported: [], updated: [], skipped: [], rejected: [], warnings: [] };
  const accepted = [];
  const seenInPack = [];

  for (const raw of pack.questions || []) {
    const edit = review.edit?.[raw.id];
    const item = { ...raw, ...(edit || {}) };
    delete item.note;

    if (review.reject?.[raw.id]) { result.rejected.push({ id: raw.id, reason: `review: ${review.reject[raw.id]}` }); continue; }

    const { errors, warnings } = validate(item);
    if (errors.length) { result.rejected.push({ id: raw.id, reason: errors.join('; ') }); continue; }

    // duplicates vs existing site content (exact text, or near-identical text with same answer)
    const dup = existing[item.grade].find(e =>
      norm(e.text) === norm(item.question) ||
      (jaccard(e.text, item.question) >= 0.85 && norm(e.answer) === norm(item.correctAnswer)));
    if (dup) { result.skipped.push({ id: raw.id, reason: `duplicate of existing ${dup.path}` }); continue; }

    // duplicates vs other imported items (other packs) and within this pack
    const otherImport = prior.find(p => p.id !== item.id && p.grade === item.grade && norm(p.question) === norm(item.question));
    if (otherImport) { result.skipped.push({ id: raw.id, reason: `duplicate of imported ${otherImport.id}` }); continue; }
    const inPack = seenInPack.find(p => p.grade === item.grade && norm(p.question) === norm(item.question) && norm(p.correctAnswer) === norm(item.correctAnswer));
    if (inPack) { result.skipped.push({ id: raw.id, reason: `duplicate within pack of ${inPack.id}` }); continue; }
    seenInPack.push(item);

    const subject = SUBJECTS[item.subject.toLowerCase()];
    const target = item.target || defaultTarget(item);
    const before = priorById.get(item.id);
    const record = {
      id: item.id,
      pack: packName,
      grade: item.grade,
      subject,
      target: target.startsWith(subject + '.') || target === 'mathWordProblems' ? target : `${subject}.quiz`,
      topic: item.topic || '',
      difficulty: item.difficulty || 'medium',
      question: item.question,
      options: item.options,
      correct: item.options.indexOf(item.correctAnswer),
      explanation: item.explanation || '',
      sourceTag: item.sourceTag || '',
      // never auto-publish: keep an existing published status only if content is unchanged
      status: 'draft',
      edited: edit ? (edit.note || 'edited in review') : undefined,
      importedAt: before?.importedAt || new Date().toISOString().slice(0, 10),
    };
    if (before && before.status === 'published') {
      const same = ['question', 'correct', 'explanation', 'target'].every(k => JSON.stringify(before[k]) === JSON.stringify(record[k]))
        && JSON.stringify(before.options) === JSON.stringify(record.options);
      if (same) record.status = 'published';
    }
    if (warnings.length) result.warnings.push({ id: item.id, warnings });
    (before ? result.updated : result.imported).push(record.id);
    accepted.push(record);
  }

  // shared generic explanations → flag for improvement
  const explCount = accepted.reduce((m, r) => (m[r.explanation] = (m[r.explanation] || 0) + 1, m), {});
  for (const r of accepted) if (r.explanation && explCount[r.explanation] >= 4)
    result.warnings.push({ id: r.id, warnings: ['generic explanation shared by ' + explCount[r.explanation] + ' items'] });

  const report = renderReport(packName, pack, result, accepted, path.relative(ROOT, reviewPath));
  if (!flag('--dry-run')) {
    const merged = [...prior.filter(p => p.pack !== packName && !accepted.some(a => a.id === p.id)), ...accepted];
    writeImports(merged);
    fs.writeFileSync(abs.replace(/\.json$/, '.report.md'), report, 'utf8');
  }
  console.log(report);
}

function renderReport(packName, pack, r, accepted, reviewRel) {
  const byKey = {};
  for (const a of accepted) { const k = `Grade ${a.grade} · ${a.subject} → ${a.target}`; byKey[k] = (byKey[k] || 0) + 1; }
  const lines = [
    `# Import report — ${packName}`, '',
    `Date: ${new Date().toISOString().slice(0, 10)}  `,
    `Source questions: ${(pack.questions || []).length}  `,
    `Review file: ${reviewRel}`, '',
    `| Result | Count |`, `|---|---|`,
    `| Imported as draft (new) | ${r.imported.length} |`,
    `| Re-imported (already present) | ${r.updated.length} |`,
    `| Skipped (duplicates) | ${r.skipped.length} |`,
    `| Rejected | ${r.rejected.length} |`, '',
    `## Placement`, ...Object.entries(byKey).map(([k, v]) => `- ${k}: ${v}`), '',
  ];
  if (r.skipped.length) lines.push('## Skipped', ...r.skipped.map(s => `- \`${s.id}\` — ${s.reason}`), '');
  if (r.rejected.length) lines.push('## Rejected', ...r.rejected.map(s => `- \`${s.id}\` — ${s.reason}`), '');
  const edited = accepted.filter(a => a.edited);
  if (edited.length) lines.push('## Edited in review', ...edited.map(a => `- \`${a.id}\` — ${a.edited}`), '');
  if (r.warnings.length) lines.push('## Warnings (review before publishing)', ...r.warnings.map(w => `- \`${w.id}\` — ${w.warnings.join('; ')}`), '');
  lines.push('## Next step', 'All imported items are **drafts**. Review them in the app: Admin → ❓ ניהול חידונים. Then publish with',
    '`node tools/import-content.mjs --publish <ids>` (or `--publish "pack:' + packName + '"`) and deploy.', '');
  return lines.join('\n');
}

// ---------- entry ----------
if (flagVal('--publish')) setStatus(flagVal('--publish'), 'published');
else if (flagVal('--unpublish')) setStatus(flagVal('--unpublish'), 'draft');
else if (args[0] && !args[0].startsWith('--')) importPack(args[0]);
else {
  console.log('Usage: node tools/import-content.mjs <pack.json> [--dry-run] | --publish <ids|pack:name> | --unpublish <ids>');
  process.exit(1);
}
