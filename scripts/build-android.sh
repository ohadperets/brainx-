#!/usr/bin/env bash
# Build the BrainX Android app (Capacitor) OUTSIDE Google Drive.
#
#   npm run android:apk     → dist/android/brainx-v<N>-debug.apk     (install on a phone for testing)
#   npm run android:aab     → dist/android/brainx-v<N>-release.aab   (upload to Google Play; needs the upload key)
#   bash scripts/build-android.sh init   (one time: create the android/ project)
#
# How it works: the repo (source of truth) is mirrored to ~/.brainx-build, where node_modules and Gradle
# output live, so Drive doesn't sync hundreds of MB. Only the finished APK/AAB is copied back to dist/.
# Version: versionCode/versionName come from APP_VERSION in version.js.
# Requirements (free): Android Studio (bundles JDK 21 + Android SDK), Node 22+.
set -euo pipefail

MODE="${1:-apk}"
REPO="$(cd "$(dirname "$0")/.." && pwd)"
WORK="${BRAINX_BUILD_DIR:-$HOME/.brainx-build}"
OUT="$REPO/dist/android"
KEYS_PROPS="${BRAINX_KEYSTORE_PROPERTIES:-$HOME/.brainx-keys/keystore.properties}"

say() { printf '\n▶ %s\n' "$*"; }
die() { printf '\n✖ %s\n' "$*" >&2; exit 1; }

# ---------- toolchain ----------
if [ "$MODE" != "init" ]; then
  if [ -z "${JAVA_HOME:-}" ] || ! "$JAVA_HOME/bin/java" -version 2>&1 | grep -qE 'version "(2[1-9]|[3-9][0-9])'; then
    for j in "/Applications/Android Studio.app/Contents/jbr/Contents/Home" \
             "$HOME/Applications/Android Studio.app/Contents/jbr/Contents/Home" \
             "$(/usr/libexec/java_home -v 21+ 2>/dev/null || true)"; do
      if [ -n "$j" ] && [ -x "$j/bin/java" ]; then export JAVA_HOME="$j"; break; fi
    done
  fi
  [ -n "${JAVA_HOME:-}" ] && "$JAVA_HOME/bin/java" -version 2>&1 | grep -qE 'version "(2[1-9]|[3-9][0-9])' \
    || die "JDK 21+ not found. Install Android Studio (it includes JDK 21) or set JAVA_HOME."
  export ANDROID_HOME="${ANDROID_HOME:-$HOME/Library/Android/sdk}"
  [ -d "$ANDROID_HOME/platforms" ] || die "Android SDK not found at $ANDROID_HOME. Open Android Studio once and finish its setup."
fi

# ---------- corporate TLS inspection (build-only) ----------
# Some networks re-sign HTTPS traffic with an organisation certificate that macOS trusts but Java
# doesn't. Build a private truststore for THIS build only: Java's default CAs + the certificates
# already installed in the macOS System keychain. Nothing system-wide changes.
setup_truststore() {
  local ts="$WORK/.java-truststore.p12"
  if [ ! -f "$ts" ] || [ /Library/Keychains/System.keychain -nt "$ts" ]; then
    mkdir -p "$WORK/.certs" && rm -f "$WORK/.certs"/*.pem "$ts"
    "$JAVA_HOME/bin/keytool" -importkeystore -noprompt -srckeystore "$JAVA_HOME/lib/security/cacerts" \
      -srcstorepass changeit -destkeystore "$ts" -deststoretype PKCS12 -deststorepass changeit >/dev/null 2>&1
    security find-certificate -a -p /Library/Keychains/System.keychain 2>/dev/null \
      | awk -v dir="$WORK/.certs" '/BEGIN CERT/{n++; f=sprintf("%s/sys-%03d.pem", dir, n)} {print > f}'
    for pem in "$WORK/.certs"/*.pem; do
      [ -f "$pem" ] || continue
      "$JAVA_HOME/bin/keytool" -importcert -noprompt -alias "$(basename "$pem" .pem)" -file "$pem" \
        -keystore "$ts" -storepass changeit >/dev/null 2>&1 || true
    done
  fi
  export JAVA_TOOL_OPTIONS="-Djavax.net.ssl.trustStore=$ts -Djavax.net.ssl.trustStorePassword=changeit -Djavax.net.ssl.trustStoreType=PKCS12"
}

# ---------- mirror the repo to the build folder ----------
say "Syncing source to $WORK"
mkdir -p "$WORK"
rsync -a --delete \
  --exclude '.git/' --exclude 'node_modules/' --exclude 'dist/' --exclude 'www/' \
  --exclude 'android/.gradle/' --exclude 'android/build/' --exclude 'android/app/build/' \
  --exclude 'android/local.properties' \
  --exclude 'android/capacitor-cordova-android-plugins/' --exclude 'android/app/src/main/assets/public/' \
  "$REPO/" "$WORK/"
cd "$WORK"

# ---------- packages (only when the lockfile changed) ----------
LOCK_HASH="$(shasum package-lock.json | cut -d' ' -f1)"
if [ ! -d node_modules ] || [ "$(cat node_modules/.lock-hash 2>/dev/null)" != "$LOCK_HASH" ]; then
  say "Installing packages"
  npm ci --no-audit --no-fund
  echo "$LOCK_HASH" > node_modules/.lock-hash
fi

# ---------- web assets ----------
say "Bundling web files"
node tools/build-web.mjs
node tools/smoke.mjs | tail -1

if [ "$MODE" = "init" ]; then
  [ -d android ] && die "android/ already exists in the repo."
  say "Creating the Android project"
  npx cap add android
  rsync -a --exclude '.gradle/' --exclude 'build/' --exclude 'app/build/' --exclude 'local.properties' \
    --exclude 'capacitor-cordova-android-plugins/' --exclude 'app/src/main/assets/public/' \
    android/ "$REPO/android/"
  echo "✔ android/ created in the repo. Review and commit it."
  exit 0
fi

say "Syncing Capacitor"
echo "sdk.dir=$ANDROID_HOME" > android/local.properties
npx cap sync android
# plugin wiring generated by `cap sync` belongs in the repo
cp android/capacitor.settings.gradle "$REPO/android/capacitor.settings.gradle"
cp android/app/capacitor.build.gradle "$REPO/android/app/capacitor.build.gradle"

VERSION="$(sed -nE "s/.*APP_VERSION = '([0-9]+)'.*/\1/p" version.js)"
[ -n "$VERSION" ] || die "Could not read APP_VERSION from version.js"
mkdir -p "$OUT"
setup_truststore
cd android

case "$MODE" in
  apk)
    say "Building debug APK (v$VERSION)"
    ./gradlew --no-daemon -q -PbrainxVersionCode="$VERSION" -PbrainxVersionName="$VERSION" assembleDebug
    cp app/build/outputs/apk/debug/app-debug.apk "$OUT/brainx-v$VERSION-debug.apk"
    echo "✔ $OUT/brainx-v$VERSION-debug.apk"
    ;;
  aab)
    [ -f "$KEYS_PROPS" ] || die "Upload key not found ($KEYS_PROPS). See ANDROID.md → 'Release signing'."
    say "Building signed release bundle (v$VERSION)"
    ./gradlew --no-daemon -q -PbrainxVersionCode="$VERSION" -PbrainxVersionName="$VERSION" \
      -PbrainxKeystoreProperties="$KEYS_PROPS" bundleRelease
    cp app/build/outputs/bundle/release/app-release.aab "$OUT/brainx-v$VERSION-release.aab"
    echo "✔ $OUT/brainx-v$VERSION-release.aab"
    ;;
  *) die "Unknown mode '$MODE' (use apk, aab or init)";;
esac
